    /** Looks up [key] in [language] (falls back to English), then applies String.format when args are given. */
    fun get(language: String, key: S, vararg args: Any): String {
        val table = when (language) { AFRIKAANS -> af; ISIZULU -> zu; else -> en }
        val template = table[key] ?: en.getValue(key)
        return if (args.isEmpty()) template else template.format(*args)
    }

